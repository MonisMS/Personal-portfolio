import type { Metadata } from "next";
import Image from "next/image";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ArrowRight, ArrowUpRight, Info } from "lucide-react";
import { SiGithub } from "react-icons/si";
import { Footer } from "@/components/site/footer";
import { PageHeader } from "@/components/site/page-header";
import { site } from "@/lib/site/config";
import { getProject, projects } from "@/lib/site/projects";
import { pageMetadata } from "@/lib/site/seo";

interface ProjectPageProps {
  params: Promise<{ slug: string }>;
}

export function generateStaticParams() {
  return projects.map((project) => ({ slug: project.slug }));
}

export async function generateMetadata({ params }: ProjectPageProps): Promise<Metadata> {
  const { slug } = await params;
  const project = getProject(slug);
  if (!project) return {};

  const title = `${project.title}: ${project.tagline}`;
  return pageMetadata({
    title,
    description: project.description,
    path: `/projects/${project.slug}`,
    // Generated by ./opengraph-image.tsx (image id "card").
    image: { url: `/projects/${project.slug}/opengraph-image/card`, alt: title },
  });
}

const buttonClass =
  "site-button";

export default async function ProjectPage({ params }: ProjectPageProps) {
  const { slug } = await params;
  const project = getProject(slug);
  if (!project) notFound();

  const index = projects.indexOf(project);
  const next = projects[(index + 1) % projects.length];

  const facts = [
    { label: "Year", value: project.year },
    { label: "Role", value: project.role },
    { label: "Context", value: project.context },
    { label: "Stack", value: project.tech.join(", ") },
  ];

  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "SoftwareSourceCode",
    name: project.title,
    description: project.description,
    codeRepository: project.githubUrl,
    programmingLanguage: project.tech,
    author: { "@type": "Person", name: site.name, url: site.url },
    ...(project.liveUrl && { url: project.liveUrl }),
  };

  return (
    <div className="site-container case-study">
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
      />
      <PageHeader backHref="/projects" backLabel="Projects" />

      <main id="main">
        <header className="page-intro case-intro">
          <p className="case-metric">{project.metric}</p>
          <h1
            className="page-title"
            style={{ "--i": 1 } as React.CSSProperties}
          >
            {project.title}
          </h1>
          <p
            className="page-lead"
            style={{ "--i": 2 } as React.CSSProperties}
          >
            {project.tagline}
          </p>
          <div
            className="rise mt-6 flex flex-wrap gap-2"
            style={{ "--i": 3 } as React.CSSProperties}
          >
            {project.liveUrl && (
              <a href={project.liveUrl} target="_blank" rel="noopener noreferrer" className={buttonClass}>
                <ArrowUpRight />
                Live demo
              </a>
            )}
            <a href={project.githubUrl} target="_blank" rel="noopener noreferrer" className={buttonClass}>
              <SiGithub />
              Source code
            </a>
          </div>
        </header>

        {project.image && (
          <div className="case-image">
            <Image
              src={project.image}
              alt={`${project.title} screenshot`}
              fill
              priority
              sizes="(min-width: 1024px) 976px, 90vw"
              className="object-cover object-top"
            />
          </div>
        )}

        <dl className="case-facts">
          {facts.map((fact) => (
            <div key={fact.label}>
              <dt className="text-muted text-sm">{fact.label}</dt>
              <dd className="text-fg mt-2 text-base leading-relaxed">{fact.value}</dd>
            </div>
          ))}
        </dl>

        <section className="case-section">
          <h2 className="section-title">Overview</h2>
          <p className="case-copy">{project.description}</p>
        </section>

        <section className="case-section">
          <h2 className="section-title">How it works</h2>
          <ul className="mt-5 space-y-3">
            {project.highlights.map((highlight) => (
              <li key={highlight} className="case-highlight">
                <span aria-hidden className="sr-only" />
                {highlight}
              </li>
            ))}
          </ul>
        </section>

        {project.note && (
          <p className="border-line bg-surface text-muted mt-10 flex gap-3 rounded-lg border p-4 text-sm leading-relaxed">
            <Info className="text-subtle mt-0.5 size-4 shrink-0" />
            {project.note}
          </p>
        )}

        <Link
          href={`/projects/${next.slug}`}
          className="case-next"
        >
          <div>
            <p className="text-subtle text-xs">Next project</p>
            <p className="font-display text-fg mt-1 text-2xl leading-none">{next.title}</p>
          </div>
          <ArrowRight className="text-subtle group-hover:text-fg size-5 transition-[color,transform] duration-200 group-hover:translate-x-1" />
        </Link>
      </main>
      <Footer />
    </div>
  );
}
